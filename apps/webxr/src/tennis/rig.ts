// A standing tennis player on any avatar's SMPL-X rig. Everything is posed procedurally from a few numbers (how the
// hips and shoulders turn, the knees bend, the trunk leans), where the racket's sweet spot is and how its face looks,
// where the left hand is and where each foot is planted: two-bone IK for the arms and legs, the racket rigidly in the
// right hand with an eastern grip, most of the forearm's roll carried by the elbow (as SMPL-X's skinning wants).
//
// Space "F": the player's own, on the floor where he stands: +Z toward the net (his front), +X his left, +Y up. The
// avatar mesh is posed directly in it (SMPL-X's rest pose already faces +Z), so the bundle's own turn is not used.

